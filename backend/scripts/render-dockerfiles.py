#!/usr/bin/env python3
"""Render all existing Docker entry points; --check reports drift without changing files."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
JDK = 'eclipse-temurin:25-jdk-jammy@sha256:d6ac622efdaafbf92f92f526910c2ea2e8312a47c3af981475eb21579513fae1'
JRE = 'eclipse-temurin:25-jre-jammy@sha256:7ea228ef5a43661c3ea8ed08e2819d8bc844d0868b255040c61db3006ca67dcd'
SERVICES = {
    'api-gateway': '8080 8090', 'product-service': '8081', 'cart-service': '8082',
    'order-service': '8083 9093', 'inventory-service': '8084 9094',
    'payment-service': '8086 9095', 'notification-service': '8087',
}
MODULES = ['build-support', 'common-lib', 'security-lib', 'proto', 'events', 'test-support', *SERVICES, 'e2e-tests']
FLAGS = '-XX:+UseCompactObjectHeaders -XX:MaxRAMPercentage=75'
HEADER = '# syntax=docker/dockerfile:1\n# Generated by backend/scripts/render-dockerfiles.py; edit the renderer, then run it.\n'


def builder(prefix, selected=None):
    text = f'FROM {JDK} AS builder\nWORKDIR /workspace\n'
    for path in ['mvnw', '.mvn', 'pom.xml', 'config']:
        text += f'COPY {prefix}{path} {path}\n'
    for module in MODULES:
        text += f'COPY {prefix}{module}/pom.xml {module}/pom.xml\n'
    text += 'RUN chmod +x mvnw\n'
    sources = ['build-support', 'common-lib', 'security-lib', 'proto', 'events', 'test-support', selected] if selected else MODULES
    for module in sources:
        text += f'COPY {prefix}{module}/src {module}/src\n'
    selection = f' -pl :{selected} -am' if selected else ''
    return text + f'RUN --mount=type=cache,target=/root/.m2 ./mvnw -B -ntp package{selection} -DskipTests -DskipITs -DskipE2ETests\n\n'


def runtime_base():
    return f'''FROM {JRE} AS runtime-base
WORKDIR /app
RUN apt-get update && apt-get install -y --no-install-recommends curl \\
    && rm -rf /var/lib/apt/lists/* \\
    && groupadd -r -g 1001 robomart && useradd -r -u 1001 -g robomart robomart \\
    && mkdir -p /tmp/robomart-images && chown robomart:robomart /app /tmp/robomart-images
USER robomart

'''


def image(service, prebuilt=False, final=None):
    extraction = f'{service}-extracted'
    source = f'COPY {service}/target/{service}-0.0.1-SNAPSHOT.jar' if prebuilt else f'COPY --from=builder /workspace/{service}/target/{service}-0.0.1-SNAPSHOT.jar'
    text = f'''FROM runtime-base AS {extraction}
{source} /tmp/application.jar
RUN java -Djarmode=tools -jar /tmp/application.jar extract --layers --application-filename application.jar --destination /tmp/extracted

FROM runtime-base AS {final or service}
'''
    for layer in ['dependencies', 'spring-boot-loader', 'snapshot-dependencies', 'application']:
        text += f'COPY --from={extraction} --chown=1001:1001 /tmp/extracted/{layer}/ ./\n'
    text += f'''# Isolated core-context training: no application scan, auto-config, migrations or external I/O.
RUN --network=none java {FLAGS} -XX:AOTCacheOutput=application.aot \\
    -Dspring.context.exit=onRefresh -Dspring.config.location=optional:classpath:/aot-training-only/ \\
    -cp application.jar com.robomart.build.AotCacheTraining
EXPOSE {SERVICES[service]}
HEALTHCHECK --interval=30s --timeout=10s --retries=3 \\
    CMD curl --fail --silent http://localhost:{'8090' if service == 'api-gateway' else SERVICES[service].split()[0]}/actuator/health/liveness || exit 1
ENTRYPOINT ["java", "-XX:+UseCompactObjectHeaders", "-XX:MaxRAMPercentage=75", "-XX:AOTCache=application.aot", "-jar", "application.jar"]

'''
    return text


def outputs():
    yield ROOT / 'backend/Dockerfile', HEADER + builder('') + runtime_base() + ''.join(image(s) for s in SERVICES)
    yield ROOT / 'backend/Dockerfile.prebuilt', HEADER + '# Context: backend/. Package service JARs before building.\n' + runtime_base() + ''.join(image(s, prebuilt=True) for s in SERVICES)
    for service in SERVICES:
        yield ROOT / f'infra/docker/{service}/Dockerfile', HEADER + '# Context: repository root (existing CD workflow).\n' + builder('backend/', service) + runtime_base() + image(service, final='runtime')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for path, content in outputs():
        if args.check:
            if not path.exists() or path.read_text() != content.rstrip() + "\n":
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content.rstrip() + "\n")
    if drift:
        parser.exit(1, 'Dockerfile drift: ' + ', '.join(drift) + '\n')
    print('Dockerfiles match the shared renderer.' if args.check else 'Rendered 9 Dockerfiles.')


if __name__ == '__main__':
    main()
